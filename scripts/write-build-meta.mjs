import { writeFile } from "node:fs/promises";

function cleanCommit(value) {
  const candidate = String(value ?? "").trim();
  return /^[0-9a-f]{7,64}$/i.test(candidate) ? candidate.toLowerCase() : "local";
}

function cleanBranch(value) {
  const candidate = String(value ?? "").trim();
  if (candidate === "") return "local";
  return candidate.replace(/[^a-zA-Z0-9._/-]/g, "-").slice(0, 120);
}

const commit = cleanCommit(
  process.env.WORKERS_CI_COMMIT_SHA
    ?? process.env.GITHUB_SHA
    ?? "local",
);
const branch = cleanBranch(
  process.env.WORKERS_CI_BRANCH
    ?? process.env.GITHUB_REF_NAME
    ?? "local",
);
const source = process.env.WORKERS_CI === "1"
  ? "cloudflare-workers-builds"
  : process.env.GITHUB_ACTIONS === "true"
    ? "github-actions"
    : "local";

const target = new URL("../src/build-meta.ts", import.meta.url);
const contents = `// Regenerated by scripts/write-build-meta.mjs during CI builds.
export const BUILD_COMMIT = ${JSON.stringify(commit)};
export const BUILD_BRANCH = ${JSON.stringify(branch)};
export const BUILD_SOURCE = ${JSON.stringify(source)};
`;

await writeFile(target, contents, "utf8");
console.log(`build metadata: ${source} ${branch} ${commit}`);
